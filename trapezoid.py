def area(a, b, h):
    """
    Вычисляет площадь трапеции с основаниями a и b
    и высотой h.

    Пример вызова:
        area(3, 5, 4)
    """
    return (a + b) * h / 2


def midline(a, b):
    """
    Вычисляет длину средней линии трапеции
    с основаниями a и b.

    Пример вызова:
        midline(3, 5)
    """
    return (a + b) / 2


def perimeter(a, b, c, d):
    """
    Вычисляет периметр трапеции по четырём сторонам.

    Пример вызова:
        perimeter(3, 5, 4, 4)
    """
    return a + b + c + d
